"""Sidebar list scrolling: trackpad and mouse-wheel gestures over the sidebar move the list, whichever
widget has focus. Gestures over the video still pan the picture. Needs a window.

The events are generated by Tk, so the bindings are the real ones the app uses.
"""

from tests import harness as h
h.setup_env()

import customtkinter as ctk  # noqa: E402
import gui.rigid.rigid_app as ra  # noqa: E402


_APP = {}


def _open_app():
    """One app for the whole module: a second RigidApp in the same process breaks Tk's images."""
    if "app" not in _APP:
        h.quiet_dialogs(ra)
        root = ctk.CTk()
        root.geometry("1280x720")
        root.update()
        app = ra.RigidApp(root, videopath=h.make_clip())
        h.pump(root, lambda: app.videoapp.fcount > 0)
        h.pump(root, timeout=0.5)
        _APP.update(root=root, app=app)
    root, app = _APP["root"], _APP["app"]
    app.sidebar_canvas.yview_moveto(0)
    app.view.reset()
    app.updateframe()
    root.update()
    return root, app


def _packed(dx, dy):
    """The TouchpadScroll delta: x in the high 16 bits, y in the low 16 (as Tk packs it)."""
    return (dx << 16) | (dy & 0xFFFF)


def test_sidebar_has_more_than_fits():
    root, app = _open_app()
    top, bottom = app.sidebar_canvas.yview()
    h.check("the sidebar list is longer than its window, so it can scroll", bottom - top < 1.0,
            f"yview {top}..{bottom}")


def test_trackpad_scroll_over_sidebar_moves_the_list():
    root, app = _open_app()
    start = app.sidebar_canvas.yview()[0]
    # Fingers move up: the list moves up, so the top of the list scrolls out of view
    app.sidebar_canvas.event_generate("<TouchpadScroll>", x=20, y=20, delta=_packed(0, -30))
    root.update()
    h.check("a trackpad scroll over the sidebar moves the list up",
            app.sidebar_canvas.yview()[0] > start, f"top {start} -> {app.sidebar_canvas.yview()[0]}")


def test_trackpad_scroll_down_at_the_top_stays_at_the_top():
    root, app = _open_app()
    app.sidebar_canvas.event_generate("<TouchpadScroll>", x=20, y=20, delta=_packed(0, 30))
    root.update()
    h.check("scrolling up at the top of the list leaves it at the top",
            app.sidebar_canvas.yview()[0] == 0.0, f"top {app.sidebar_canvas.yview()[0]}")


def test_mouse_wheel_over_sidebar_moves_the_list():
    root, app = _open_app()
    start = app.sidebar_canvas.yview()[0]
    app.sidebar_canvas.event_generate("<MouseWheel>", x=20, y=20, delta=-1)
    root.update()
    h.check("a mouse-wheel notch over the sidebar moves the list",
            app.sidebar_canvas.yview()[0] > start, f"top {start} -> {app.sidebar_canvas.yview()[0]}")


def test_sidebar_scrolls_while_video_has_focus():
    root, app = _open_app()
    app.videoview.focus_force()
    root.update()
    start = app.sidebar_canvas.yview()[0]
    app.sidebar_canvas.event_generate("<TouchpadScroll>", x=20, y=20, delta=_packed(0, -30))
    root.update()
    h.check("the sidebar scrolls even when the video view has focus",
            app.sidebar_canvas.yview()[0] > start, f"top {start} -> {app.sidebar_canvas.yview()[0]}")


def test_gesture_over_video_does_not_move_the_sidebar():
    root, app = _open_app()
    start = app.sidebar_canvas.yview()[0]
    app.videoview.event_generate("<TouchpadScroll>", x=100, y=100, delta=_packed(0, -30))
    root.update()
    h.check("a gesture over the video leaves the sidebar where it was",
            app.sidebar_canvas.yview()[0] == start, f"top {start} -> {app.sidebar_canvas.yview()[0]}")


def test_gesture_over_video_still_pans_the_picture():
    root, app = _open_app()
    app.view.set_zoom(2.0)
    app.view.set_fraction(0.5, 0.5)
    app.updateframe()
    root.update()
    oy = app.view.oy
    app.videoview.event_generate("<TouchpadScroll>", x=100, y=100, delta=_packed(0, 10))
    root.update()
    h.check("a downward two-finger scroll over the video still moves the picture",
            app.view.oy != oy, f"oy {oy} -> {app.view.oy}")


if __name__ == "__main__":
    h.run_tests([test_sidebar_has_more_than_fits,
                 test_trackpad_scroll_over_sidebar_moves_the_list,
                 test_trackpad_scroll_down_at_the_top_stays_at_the_top,
                 test_mouse_wheel_over_sidebar_moves_the_list,
                 test_sidebar_scrolls_while_video_has_focus,
                 test_gesture_over_video_does_not_move_the_sidebar,
                 test_gesture_over_video_still_pans_the_picture])
